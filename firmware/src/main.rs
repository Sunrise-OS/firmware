//! tinted-boot's AArch64 machine bring-up and Patina DXE handoff.
//!
//! The reset stage runs on QEMU's `virt` machine, sets up RAM, translation,
//! console, interrupts and the device tree, then loads Patina's DXE core from
//! the firmware volume in flash. Patina publishes the UEFI services and platform
//! tables and installs the volume's FV protocols from the handoff HOB.
//!
//! Bring-up order matters: the reset trampoline copies the ELF and FV to RAM;
//! the entry sets a stack and exception vectors; the MMU gives RAM Normal memory
//! attributes instead of reset's Device-nGnRnE; then the console and HOB list
//! can be built before Patina starts.

